"""Heads-up push/fold equilibrium ("GTO" short-stack charts), solved from scratch.

The game: both players have S big blinds. The small blind (button) either folds, losing
its 0.5 bb, or goes all-in. The big blind then folds (losing 1 bb) or calls, and the
hand is run out. With only these choices the exact equilibrium can be computed:
fictitious play (each side repeatedly best-responds to the other's average strategy)
converges to it, and the exploitability number below shows how close it got (0 = perfect).

    python solver/pushfold.py                 # solve 1-25 bb, write bots/pushfold_table.py
    python solver/pushfold.py --show 10       # print the 10 bb ranges as a grid
"""

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from cards import RANKS  # noqa: E402

DEPTHS = [x / 2 for x in range(2, 51)]  # 1, 1.5, ... 25 bb


def load(path=ROOT / "solver" / "preflop_equity.npz"):
    d = np.load(path)
    return [str(n) for n in d["names"]], d["equity"], d["weight"]


def sb_values(E, W, q, S):
    """EV (in bb) of pushing each hand against big-blind calling frequencies q."""
    payoff = (1 - q)[None, :] * 1.0 + q[None, :] * (E * 2 * S - S)
    return (W * payoff).sum(1) / W.sum(1)


def bb_call_values(E, W, p, S):
    """Big blind's EV of calling with each hand against small-blind push frequencies p."""
    w = W * p[:, None]
    tot = w.sum(0)
    ev = (w * ((1 - E) * 2 * S - S)).sum(0) / np.where(tot > 0, tot, 1)
    return np.where(tot > 0, ev, -np.inf)


def game_value(E, W, p, q, S):
    """Small blind's average EV over all deals."""
    push = (1 - q)[None, :] * 1.0 + q[None, :] * (E * 2 * S - S)
    per = (1 - p)[:, None] * -0.5 + p[:, None] * push
    return float((W * per).sum() / W.sum())


def exploitability(E, W, p, q, S):
    """How much (bb per hand, summed over both sides) best responses gain vs (p, q)."""
    br_p = (sb_values(E, W, q, S) > -0.5).astype(float)
    br_q = (bb_call_values(E, W, p, S) > -1.0).astype(float)
    return game_value(E, W, br_p, q, S) - game_value(E, W, p, br_q, S)


def solve(E, W, S, iters=3000):
    n = len(E)
    p = np.full(n, 0.5)
    q = np.full(n, 0.5)
    for t in range(1, iters + 1):
        br_p = (sb_values(E, W, q, S) > -0.5).astype(float)
        br_q = (bb_call_values(E, W, p, S) > -1.0).astype(float)
        p += (br_p - p) / (t + 1)
        q += (br_q - q) / (t + 1)
    return p, q, exploitability(E, W, p, q, S)


def grid(names, freq):
    """13x13 chart: pairs on the diagonal, suited above it, offsuit below."""
    idx = {nm: i for i, nm in enumerate(names)}
    rows = []
    for a in range(12, -1, -1):
        row = []
        for b in range(12, -1, -1):
            if a == b:
                nm = RANKS[a] * 2
            elif b < a:
                nm = RANKS[a] + RANKS[b] + "s"
            else:
                nm = RANKS[b] + RANKS[a] + "o"
            f = freq[idx[nm]]
            row.append(f"{nm:>4}" if f >= 0.5 else "   .")
        rows.append(" ".join(row))
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", type=float, help="print the ranges for this many bb")
    ap.add_argument("--iters", type=int, default=3000)
    args = ap.parse_args()
    names, E, W = load()
    combos = W.sum(1)  # proportional to how often each type is dealt
    combos = combos / combos.sum()

    if args.show:
        p, q, expl = solve(E, W, args.show, args.iters)
        print(f"{args.show:g} bb: small blind pushes {(p * combos).sum():.1%} of hands, "
              f"big blind calls {(q * combos).sum():.1%}  (exploitability {expl:.5f} bb)")
        print("\nSMALL BLIND PUSH:\n" + grid(names, p))
        print("\nBIG BLIND CALL:\n" + grid(names, q))
        return

    push_max = {nm: 0.0 for nm in names}
    call_max = {nm: 0.0 for nm in names}
    worst = 0.0
    for S in DEPTHS:
        p, q, expl = solve(E, W, S, args.iters)
        worst = max(worst, expl)
        for i, nm in enumerate(names):
            if p[i] >= 0.5:
                push_max[nm] = S
            if q[i] >= 0.5:
                call_max[nm] = S
        print(f"{S:5.1f} bb: push {(p * combos).sum():6.1%}  call {(q * combos).sum():6.1%}"
              f"  exploitability {expl:.5f} bb")
    out = ROOT / "bots" / "pushfold_table.py"
    with open(out, "w") as f:
        f.write('"""Generated by solver/pushfold.py: heads-up push/fold equilibrium.\n\n'
                "PUSH[hand] = largest stack (in big blinds, up to 25) at which the small\n"
                "blind goes all-in with it; CALL[hand] = largest stack at which the big blind\n"
                'calls an all-in with it. 25 means "at every depth solved".\n"""\n\n')
        f.write(f"MAX_DEPTH = {DEPTHS[-1]}\n\n")
        for label, table in (("PUSH", push_max), ("CALL", call_max)):
            f.write(f"{label} = {{\n")
            for k in range(0, len(names), 8):
                f.write("    " + " ".join(f'"{nm}": {table[nm]:g},'
                                          for nm in names[k:k + 8]) + "\n")
            f.write("}\n\n")
    print(f"worst exploitability {worst:.5f} bb per hand; wrote {out}")


if __name__ == "__main__":
    main()
