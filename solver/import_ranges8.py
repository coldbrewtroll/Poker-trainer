"""Turns exported solver ranges into bots/range_table8.py for the 8-max bot.

One file per (spot, action), named  <spot>@<bb>__<action>.<ext>  (two underscores), e.g.

    UTG@100__raise_2.3bb.txt          UTG opens to 2.3 bb
    BTN_UTGr@100__call.txt            BTN calls an UTG open
    BTN_UTGr@100__raise_3x.txt        BTN 3-bets an UTG open to 3x
    UTG_UTGr_BTNr@100__call.txt       UTG calls the BTN 3-bet
    BB_SBr@40__call.txt               big blind calls the small blind's open

Spot names: the hero's position, then each earlier preflop action that wasn't a fold, as
<position><r|c|a> (raise, call, all-in). Positions: UTG UTG1 LJ HJ CO BTN SB BB.
Heads-up file names (sb_first, bb_vs_raise, ...) are accepted too and mean the
blind-vs-blind spots, so a heads-up SB-vs-BB sim works as is.
Actions and range formats: as in solver/import_ranges.py.

    python solver/import_ranges8.py my_ranges
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from bots.lines import parse_action  # noqa: E402
from bots.lines8 import parse_spot  # noqa: E402
from solver.import_ranges import COMBOS, TYPES, parse  # noqa: E402


def load_folder(folder):
    table = {}
    if Path(folder).name.lower() == "study_ranges" and __name__ == "__main__":
        sys.exit("study_ranges is for the trainer only (it reads that folder by itself); "
                 "import your own sims from my_ranges")
    for f in sorted(Path(folder).glob("*")):
        if not f.is_file() or "__" not in f.stem:
            continue
        spot_part, action_name = f.stem.split("__", 1)
        spot_name, _, depth = spot_part.partition("@")
        try:
            depth = float(depth.lower().removesuffix("bb")) if depth else 0.0
        except ValueError:
            depth = -1
        spot, action = parse_spot(spot_name), parse_action(action_name)
        if spot is None or action is None or depth < 0:
            print(f"skipped {f.name}: expected <spot>@<bb>__<action>, e.g. "
                  "BTN_UTGr@100__call.txt (see the top of this script)")
            continue
        try:
            rng = parse(f.read_text(encoding="utf-8", errors="replace"))
        except ValueError as e:
            print(f"skipped {f.name}: {e}")
            continue
        table.setdefault(spot, {}).setdefault(depth, {})[action] = rng
        share = sum(rng.get(t, 0) * COMBOS[t] for t in TYPES) / 1326
        at = f"@{depth:g}bb" if depth else ""
        print(f"{spot + at:28s} {action:12s} {share:6.1%} of hands")
    for spot, depths in table.items():
        for depth, acts in depths.items():
            for t in TYPES:
                total = sum(a.get(t, 0) for a in acts.values())
                if total > 1.02:
                    print(f"warning: {spot}@{depth:g} {t} adds up to {total:.0%} across actions")
    return table


def write(table, out):
    with open(out, "w") as f:
        f.write('"""Generated by solver/import_ranges8.py from your own solver exports.\n'
                'TABLE[spot][stack depth in bb, 0 = any][action][hand type] = how often\n'
                'to take that action. Spot names: see bots/lines8.py."""\n\n')
        f.write("TABLE = {\n")
        for spot, depths in table.items():
            f.write(f"    {spot!r}: {{\n")
            for depth, acts in sorted(depths.items()):
                f.write(f"        {depth:g}: {{\n")
                for action, rng in acts.items():
                    items = ", ".join(f"{t!r}: {v:g}" for t, v in rng.items() if v > 0)
                    f.write(f"            {action!r}: {{{items}}},\n")
                f.write("        },\n")
            f.write("    },\n")
        f.write("}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--out", default=str(ROOT / "bots" / "range_table8.py"))
    args = ap.parse_args()
    table = load_folder(args.folder)
    write(table, args.out)
    print(f"wrote {args.out} ({len(table)} spots)")


if __name__ == "__main__":
    main()
