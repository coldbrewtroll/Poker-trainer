"""Builds bots/preflop_data.py from the equity table: plain Python data, so bots need no
numpy or files at run time.

    TOP[hand]          where the hand ranks among all 1326 combos, as the share of combos
                       at least as strong (AA ~0.005 ... 32o ~1.0), ranked by equity vs a
                       random hand
    EQ_VS_TOP[p][hand] all-in equity against the strongest p% of hands (p = 2, 4, ... 100),
                       with card removal

    python solver/build_preflop_tables.py
"""

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from solver.pushfold import load  # noqa: E402

PCTS = list(range(2, 101, 2))


def main():
    names, E, W = load()
    combos = W.sum(1)
    vs_random = (E * W).sum(1) / combos
    order = np.argsort(-vs_random)
    cum = np.cumsum(combos[order]) / combos.sum()
    top = {names[i]: float(cum[k]) for k, i in enumerate(order)}

    eq_vs_top = {}
    for pct in PCTS:
        in_range = np.array([1.0 if top[n] <= pct / 100 + 1e-9 else 0.0 for n in names])
        if in_range.sum() == 0:
            in_range[order[0]] = 1.0
        w = W * in_range[None, :]
        eq = (E * w).sum(1) / np.where(w.sum(1) > 0, w.sum(1), 1)
        eq_vs_top[pct] = {n: round(float(eq[i]), 4) for i, n in enumerate(names)}

    out = ROOT / "bots" / "preflop_data.py"
    with open(out, "w") as f:
        f.write('"""Generated by solver/build_preflop_tables.py (see there for what it is)."""\n\n')
        f.write("PCTS = " + repr(PCTS) + "\n\n")
        f.write("TOP = {\n")
        for k in range(0, len(names), 8):
            f.write("    " + " ".join(f"{n!r}: {top[n]:.4f}," for n in names[k:k + 8]) + "\n")
        f.write("}\n\nEQ_VS_TOP = {\n")
        for pct in PCTS:
            items = ", ".join(f"{n!r}: {v}" for n, v in eq_vs_top[pct].items())
            f.write(f"    {pct}: {{{items}}},\n")
        f.write("}\n")
    best = sorted(top, key=top.get)
    print("strongest:", " ".join(best[:10]), "| weakest:", " ".join(best[-5:]))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
